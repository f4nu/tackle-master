"""Regenerates Data.lua from WoW Forever's game tables on wago.tools.

    python tools/gen_data.py [build]

Everything is item and spell IDs, so it holds in every client language. The
build defaults to the newest WoW Forever (wowf) build wago.tools knows.
"""
import collections
import csv
import io
import json
import os
import sys
import urllib.request

UA = {"User-Agent": "Mozilla/5.0"}
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "Data.lua")

FISHING_SKILL = "356"
BOBBER = "35591"  # game object a fishing cast summons

# A pole's fishing bonus is a scaled item stat the tables don't spell out,
# so it is kept here. Poles not listed count as +0 and rank by item level.
POLE_BONUS = {
    6256: 0,  # Fishing Pole
    6365: 5,  # Strong Fishing Pole
    6366: 15,  # Darkwood Fishing Pole
    6367: 20,  # Big Iron Fishing Pole
    12225: 3,  # Blump Family Fishing Pole
    19022: 25,  # Nat Pagle's Extreme Angler FC-5000
    19970: 35,  # Arcanite Fishing Pole
}

# Containers that are fished up. Loot tables aren't in the client data, so
# this is kept by hand; the add-on also learns any fished item that opens.
SEA = [
    5523, 5524, 7973, 15874,  # clams
    6307, 6351, 6352, 6353, 6354, 6355, 6356, 6357, 13874, 13875, 13918,
    20708, 21113, 21150, 21228,  # bottles, crates, chests, trunks
]


def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA)) as r:
        return r.read().decode("utf-8")


def table(name, build):
    text = fetch(f"https://wago.tools/db2/{name}/csv?build={build}")
    return list(csv.DictReader(io.StringIO(text)))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else json.loads(fetch("https://wago.tools/api/builds"))["wowf"][0]["version"]
    items = {r["ID"]: r for r in table("Item", build)}
    sparse = {r["ID"]: r for r in table("ItemSparse", build)}
    effects = {r["ID"]: r for r in table("ItemEffect", build)}
    enchants = {r["ID"]: r for r in table("SpellItemEnchantment", build)}
    spell_effects = collections.defaultdict(list)
    for r in table("SpellEffect", build):
        spell_effects[r["SpellID"]].append(r)

    def need(item):
        s = sparse[item]
        skill = int(s["RequiredSkillRank"]) if s["RequiredSkill"] == FISHING_SKILL else 0
        return int(s["RequiredLevel"]), skill, int(s["ItemLevel"])

    # Fishing casts: every spell that summons the bobber.
    fishing = sorted(int(s) for s, es in spell_effects.items()
                     if any(e["Effect"] == "50" and e["EffectMiscValue_0"] == BOBBER for e in es))

    # Poles: weapons of subclass 20 that exist in this client.
    poles = {}
    for id, it in items.items():
        if it["ClassID"] == "2" and it["SubclassID"] == "20" and id in sparse:
            poles[int(id)] = (POLE_BONUS.get(int(id), 0),) + need(id)

    # Lures: an on-use spell putting a temporary enchant (effect 54) whose
    # equip spell raises fishing skill (aura 30 on skill 356).
    def lure_bonus(spell):
        for e in spell_effects[spell]:
            if e["Effect"] != "54":
                continue
            en = enchants.get(e["EffectMiscValue_0"])
            if not en:
                continue
            for k in range(3):
                if en[f"Effect_{k}"] != "3":
                    continue
                for a in spell_effects[en[f"EffectArg_{k}"]]:
                    if a["EffectAura"] == "30" and a["EffectMiscValue_0"] == FISHING_SKILL:
                        return round(float(a["EffectBasePointsF"]))
        return None

    lures = {}
    for r in table("ItemXItemEffect", build):
        effect = effects.get(r["ItemEffectID"])
        if not effect or effect["TriggerType"] != "0" or r["ItemID"] not in sparse:
            continue
        bonus = lure_bonus(effect["SpellID"])
        if bonus:
            lures[int(r["ItemID"])] = (bonus,) + need(r["ItemID"])

    # Clams by their English name, read here so the add-on needs no text.
    # Locked boxes need a lockpick or key first and are left alone.
    sea = {}
    for id in SEA:
        row = sparse[str(id)]
        sea[id] = ('"clam"' if "Clam" in row["Display_lang"] else '"chest"', "true" if row["LockID"] != "0" else "false")

    def entries(d):
        return "".join(f"\t[{k}] = {{ {', '.join(map(str, v))} }},\n" for k, v in sorted(d.items()))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(f"-- Generated by tools/gen_data.py from WoW Forever {build}. Do not edit.\n")
        f.write("local _, ns = ...\n\n")
        f.write(f'ns.DATA_BUILD = "{build}"\n\n')
        f.write("-- Spells that cast the bobber.\nns.FISHING = {\n")
        f.write("".join(f"\t[{s}] = true,\n" for s in fishing))
        f.write("}\n\n-- item = { fishing bonus, required level, required fishing skill, item level }\n")
        f.write("ns.POLES = {\n" + entries(poles) + "}\n\n")
        f.write("ns.LURES = {\n" + entries(lures) + "}\n\n")
        f.write("-- item = { kind, locked }\nns.SEA = {\n" + entries(sea) + "}\n")
    print(f"{build}: {len(fishing)} fishing spells, {len(poles)} poles, {len(lures)} lures, {len(sea)} sea containers")


if __name__ == "__main__":
    main()
